def list_voices() -> list[dict[str, Any]]:
    from backend_service import voice_library  # noqa: PLC0415

    return [_public(item) for item in voice_library.list_items(kind="clone")]


def get_voice(voice_id: str) -> dict[str, Any] | None:
    from backend_service import voice_library  # noqa: PLC0415

    if not voice_library.is_valid_id(voice_id):
        return None
    item = voice_library.get(voice_id)
    return item if item and item.get("kind") == "clone" and item.get("consent") else None


def _public(item: dict[str, Any]) -> dict[str, Any]:
    record = item.get("consent") or {}
    return {
        "id": item["id"],
        "name": item.get("title"),
        "createdAt": item.get("createdAt"),
        "durationS": item.get("durationS"),
        "referenceText": item.get("text", item.get("preview", "")),
        "consent": {k: record.get(k) for k in ("speakerName", "basis", "consentedAt", "appVersion", "code")},
    }


def create_voice(
    *,
    challenge_id: str,
    name: str,
    consent_audio: Path,
    consent_ext: str,
    reference_audio: Path | None,
    reference_ext: str | None,
    reference_text: str | None,
    statement_accepted: bool,
    origin: str,
    transcribe: Any,
) -> dict[str, Any]:
    """Check the consent recording and save the voice. ``transcribe(path) -> {"text", "durationS"}``.

    Raises ValueError with a plain message when a check fails. Without a separate reference
    recording, the consent recording is the reference.
    """
    from backend_service import voice_library  # noqa: PLC0415

    if not statement_accepted:
        raise ValueError("Confirm that this is your own voice or that the speaker gave permission.")
    challenge = consent.peek(challenge_id)
    if challenge is None:
        raise ValueError("The consent sentence expired. Start again to get a new code.")
    heard = transcribe(consent_audio)
    problem = consent.verify(str(heard.get("text") or ""), challenge["code"])
    if problem:
        safety.audit("consent-rejected", origin=origin, code=challenge["code"])
        raise ValueError(problem)

    if reference_audio is None:
        reference = heard
        ref_path, ref_ext = consent_audio, consent_ext
    else:
        reference = transcribe(reference_audio)
        ref_path, ref_ext = reference_audio, reference_ext or ".wav"
    duration = float(reference.get("durationS") or 0.0)
    if duration < MIN_REFERENCE_S or duration > MAX_REFERENCE_S:
        raise ValueError(f"The voice sample must be 3 to 30 seconds long; this one is {duration:.1f} s.")
    text = " ".join(str(reference_text or "").split()) or " ".join(str(reference.get("text") or "").split())
    if not text:
        raise ValueError("No speech was heard in the voice sample.")

    record = {
        "speakerName": challenge["speakerName"],
        "basis": challenge["basis"],
        "code": challenge["code"],
        "sentence": challenge["sentence"],
        "transcript": str(heard.get("text") or ""),
        "consentedAt": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
        "referenceSha256": safety.sha256_file(ref_path),
        "consentAudioSha256": safety.sha256_file(consent_audio),
        "appVersion": _app_version(),
        "statementAccepted": True,
        "origin": origin,
    }
    # The consent recording is kept beside the voice even when it is also the reference.
    with tempfile.TemporaryDirectory(prefix="chaosengine-clone-") as folder:
        ref_copy = Path(folder) / f"reference{ref_ext}"
        shutil.copyfile(ref_path, ref_copy)
        item = voice_library.create(
            "clone",
            {"title": " ".join(name.split())[:80] or challenge["speakerName"], "text": text,
             "durationS": round(duration, 2), "consent": record},
            audio_file=ref_copy,
            audio_ext=ref_ext,
            consent_file=consent_audio,
            consent_ext=consent_ext,
        )
    consent.consume(challenge_id)
    safety.audit("create", origin=origin, voiceId=item["id"], basis=record["basis"],
                 referenceSha256=record["referenceSha256"])
    return _public(item)


def delete_voice(voice_id: str) -> bool:
    """Delete the voice, its sample, its consent recording and record (the Library logs it)."""
    from backend_service import voice_library  # noqa: PLC0415

    if get_voice(voice_id) is None:
        return False
    return voice_library.delete(voice_id)


# ---------------------------------------------------------------------------
# Speaking
# ---------------------------------------------------------------------------

def speak(voice_id: str, text: str, model_key: str | None, *, disclaimer: bool, origin: str) -> dict[str, Any]:
    """Speak ``text`` with a cloned voice; returns the saved Library item (``speech``, ``clonedVoice``)."""
    from backend_service import voice_library  # noqa: PLC0415
    from backend_service.voice_client import get_worker  # noqa: PLC0415

    voice = get_voice(voice_id)
    if voice is None:
        raise LookupError("Cloned voice not found. Its consent record is missing or it was deleted.")
    text = text.strip()
    if not text:
        raise ValueError("Text is required.")
    if len(text) > MAX_TEXT_CHARS:
        raise ValueError(f"Cloned speech takes up to {MAX_TEXT_CHARS} characters at a time.")
    if not available_here():
        raise ValueError("Voice cloning runs on Apple Silicon Macs for now.")
    if not voice_env.is_installed():
        raise RuntimeError("The voice pack is not installed. Install it from Voice > Models.")
    row = clone_model(model_key)
    folder = snapshot_dir(row)
    if folder is None:
        raise RuntimeError(f"{row['name']} is not downloaded. Download it in Clone a voice first.")
    if not voice_env.watermark_installed():
        raise RuntimeError(safety.WATERMARK_MISSING)
    reference = voice_library.audio_path(voice_id)
    if reference is None:
        raise RuntimeError("This voice's sample is missing. Delete the voice and make it again.")

    spoken = f"{DISCLAIMER_LINE}\n{text}" if disclaimer else text
    reply = get_worker().request(
        "synthesize",
        timeout=900.0,
        engine=row["engine"],
        source=str(folder),
        text=spoken,
        refAudioPath=str(reference),
        refText=str(voice.get("text") or ""),
    )
    wav = base64.b64decode(reply["wavB64"])
    duration = float(reply.get("durationS") or 0.0)
    version = _app_version()
    with tempfile.TemporaryDirectory(prefix="chaosengine-cloned-") as tmp:
        out = Path(tmp) / "speech.wav"
        out.write_bytes(wav)
        safety.apply_watermark(out)
        tagged = safety.tag_wav(
            out.read_bytes(),
            {"appVersion": version, "model": row["repo"], "engine": row["engine"],
             "createdAt": time.strftime("%Y-%m-%dT%H:%M:%S%z"), "voiceId": voice_id,
             "disclaimer": bool(disclaimer), "watermark": "audioseal-0.2.1:CE5A"},
            f"ChaosEngineAI {version}",
        )
        out.write_bytes(tagged)
        item = voice_library.create(
            "speech",
            {"text": text, "title": f"{voice.get('title')}: {' '.join(text.split())[:40]}",
             "voice": f"clone:{voice_id}", "model": row["repo"], "durationS": round(duration, 2),
             "clonedVoice": True, "cloneVoiceId": voice_id},
            audio_file=out,
            audio_ext=".wav",
        )
    safety.audit("speak", origin=origin, voiceId=voice_id, libraryId=item["id"], model=row["key"],
                 textLength=len(text), outputSha256=safety.sha256_bytes(tagged), disclaimer=bool(disclaimer))
    return {**item, "seconds": reply.get("seconds")}
