#!/usr/bin/env python3
"""Write release-constraints.txt from the environment the app is tested in.

Release builds used to ``pip install mlx mlx-lm huggingface_hub ...`` with no
versions, so each build bundled whatever was newest that day: v0.9.8 shipped
huggingface_hub 2.2.0, mlx 0.32.4 and transformers 5.20.2 while development and
tests ran 1.33 / 0.31.2 / 5.5.3. The release workflow and stage-runtime now
install with ``-c release-constraints.txt``, which pins every package to the
version in this environment. Rerun this after upgrading a dependency here and
commit the file with the upgrade:

    .venv/bin/python scripts/freeze-release-constraints.py

Editable installs, direct git / URL references and the app's own package are
left out (pip constraints cannot express them; stage-runtime pins git
dependencies itself).
"""
from __future__ import annotations

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "release-constraints.txt"
SKIP_NAMES = {"chaosengine-ai", "chaosengine_ai", "chaos-engine-compressor", "pip", "setuptools", "wheel"}


def main() -> int:
    frozen = subprocess.run(
        [sys.executable, "-m", "pip", "freeze", "--exclude-editable"],
        capture_output=True, text=True, check=True,
    ).stdout.splitlines()
    pins = []
    for line in frozen:
        line = line.strip()
        if not line or line.startswith("-e") or " @ " in line or "==" not in line:
            continue
        name = line.split("==", 1)[0].lower()
        if name in SKIP_NAMES:
            continue
        pins.append(line)
    pins.sort(key=str.lower)
    header = (
        "# Generated by scripts/freeze-release-constraints.py from the tested environment.\n"
        f"# Python {sys.version.split()[0]}. Do not edit by hand; rerun the script after an upgrade.\n"
    )
    OUT.write_text(header + "\n".join(pins) + "\n", encoding="utf-8")
    print(f"wrote {OUT.name}: {len(pins)} pins")
    return 0


if __name__ == "__main__":
    sys.exit(main())
